-- macOS-style pointer acceleration for the touchpads only (Umbriel's
-- [input.touchpad] accel_profile; its derivation is in home/umbriel/config.toml).
-- Hyprland's accel_profile is global, so it is set per device: every pointer
-- whose name says trackpad/touchpad, checked again as devices come and go.
local TRACKPAD_ACCEL = "custom 0.75 0.000 0.044 0.114 0.224 0.381 0.592 0.856 1.174 1.541 1.956 2.412 2.907 3.436 3.994 4.578 5.185 5.811 6.453 7.109 7.777 8.455 9.142 9.836 10.535 11.240 11.949 12.661 13.376 14.093 14.811 15.531 16.253 16.974 17.696 18.419 19.142 19.864 20.586 21.309 22.030 22.752 23.472 24.193 24.913 25.632 26.350 27.068 27.786 28.502 29.218 29.933 30.648 31.362 32.075 32.788 33.500 34.211 34.922 35.632 36.342 37.051 37.759 38.467 39.174"
-- Flat scroll curve equal to libinput's adaptive touchpad scrolling.
local TRACKPAD_SCROLL = "1 0 0.2238"
-- The Magic Trackpad by its known name ("Apple Inc. Magic Trackpad"); the
-- scan below covers any other touchpad.
local configured_pads = { ["apple-inc.-magic-trackpad"] = true }
hl.device({ name = "apple-inc.-magic-trackpad", accel_profile = TRACKPAD_ACCEL, scroll_points = TRACKPAD_SCROLL })
local function configure_trackpads()
    for _, dev in ipairs(hl.get_devices() or {}) do
        local name = dev.name or ""
        if (name:find("trackpad") or name:find("touchpad")) and not configured_pads[name] then
            configured_pads[name] = true
            hl.device({ name = name, accel_profile = TRACKPAD_ACCEL, scroll_points = TRACKPAD_SCROLL })
        end
    end
end
-- Not at parse time: devices and the event loop do not exist yet then
-- (hl.get_devices() or hl.timer() there crash `Hyprland --verify-config`).
-- The 5 s re-check catches a Bluetooth trackpad that connects later. Each
-- reload builds a new Lua state (and drops its timers), so config.reloaded
-- starts it again. No monitors means `--verify-config`: nothing to do.
local function watch_trackpads()
    if #(hl.get_monitors() or {}) == 0 then
        return
    end
    configure_trackpads()
    if not trackpad_timer then
        trackpad_timer = hl.timer(configure_trackpads, { timeout = 5000, type = "repeat" })
    end
end
hl.on("hyprland.start", watch_trackpads)
hl.on("config.reloaded", watch_trackpads)

