-- Inside the overview (ScrollOverview's submap): arrows/WASD move the
-- selection, Return picks, Esc closes; the Caps layer keeps working.
if hl.plugin.scrolloverview then
    local so = hl.plugin.scrolloverview
    hl.define_submap("scrolloverview", function()
        for key, dir in pairs({ left = "left", right = "right", up = "up", down = "down", A = "left", D = "right", W = "up", S = "down" }) do
            hl.bind(key, so.navigate(dir))
        end
        hl.bind("Return", so.overview("select"))
        hl.bind("Escape", so.overview("off"))
        hl.bind(CAPS .. " + grave", so.overview("off"))
        hl.bind("mouse:272", function()
            so.overview("select")
            so.window("select")
            so.overview("off")
        end, { mouse = true })
        hl.bind("mouse:274", so.window("close"), { mouse = true })
    end)
end
