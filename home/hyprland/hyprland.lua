local function active_class()
    local w = hl.get_active_window()
    return w and (w.class or ""):lower() or ""
end

-- Caps+Q: chat and music go to the scratchpad, everything else closes.
local function caps_q()
    local class = active_class()
    if class == "" then
        return
    end
    if class:find("discord") or class:find("spotify") then
        hl.dispatch(hl.dsp.window.move({ workspace = "special:scratchpad", follow = false }))
    else
        hl.dispatch(hl.dsp.window.close())
    end
end

-- Focus the first/last column of the workspace (by x position).
local function focus_edge_column(last)
    local ws = hl.get_active_workspace()
    if not ws then
        return
    end
    local best
    for _, w in ipairs(hl.get_workspace_windows(ws) or {}) do
        if not w.floating then
            local x = type(w.at) == "table" and (w.at.x or w.at[1]) or 0
            if not best or (last and x > best.x) or (not last and x < best.x) then
                best = { win = w, x = x }
            end
        end
    end
    if best then
        hl.dispatch(hl.dsp.focus({ window = best.win }))
    end
end

-- Move the focused column to the first/last position.
local function move_column_to_edge(last)
    local ws = hl.get_active_workspace()
    local n = ws and #(hl.get_workspace_windows(ws) or {}) or 0
    for _ = 1, n do
        hl.dispatch(layout(last and "swapcol r" or "swapcol l"))
    end
end

-- Alt+Print: screenshot of the focused window (umbriel-screenshot-window).
local function screenshot_window()
    local w = hl.get_active_window()
    if not w or type(w.at) ~= "table" or type(w.size) ~= "table" then
        return
    end
    local x, y = w.at.x or w.at[1], w.at.y or w.at[2]
    local sw, sh = w.size.x or w.size[1], w.size.y or w.size[2]
    hl.exec_cmd(string.format(
        "mkdir -p \"$HOME/Pictures/Screenshots\" && grim -g '%d,%d %dx%d' \"$HOME/Pictures/Screenshots/Screenshot from $(date '+%%Y-%%m-%%d %%H-%%M-%%S').png\"",
        x, y, sw, sh))
end

-- Scratchpad window back onto the current workspace.
local function restore_from_scratchpad()
    local ws = hl.get_active_workspace()
    if ws then
        hl.dispatch(hl.dsp.window.move({ workspace = ws.id }))
    end
end

