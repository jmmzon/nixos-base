"""erebor-modes: desktop modes that turn items down and put them back.

A mode is active while its condition holds: the power profile is
"power-saver", a toggle is on, or a game runs (a Steam game or a fullscreen
window; `watch` polls for it). The manifest (generated by modules/erebor-modes.nix)
lists each mode's items; every item has a handler that can read, apply and
restore one thing (a Noctalia setting, an Umbriel include, WLED brightness, DDC
brightness, a plugin's pause, a command pair).

`sync` reconciles: items of active modes are applied once (their original value
saved), items no longer wanted are restored. A value the user changed by hand
since it was applied is left alone. The outcome is written to state.json for
the surfaces (Noctalia plugins, glass tuner, dashboard) to read.
"""

import argparse
import contextlib
import datetime
import fcntl
import json
import os
import re
import shutil
import subprocess
import sys
import time
import urllib.request

with open(os.environ["EREBOR_MODES_MANIFEST"]) as _f:
    MANIFEST = json.load(_f)
STATE_DIR = os.path.expanduser(
    os.environ.get("EREBOR_MODES_STATE_DIR") or "~/.local/state/erebor-modes"
)
STATE = os.path.join(STATE_DIR, "state.json")
SAVED = os.path.join(STATE_DIR, "saved.json")
# Modes switched by hand (kind "toggle", e.g. reduce-transparency); kept across reboots.
TOGGLES = os.path.join(STATE_DIR, "toggles.json")


def log(msg):
    print(f"erebor-modes: {msg}", file=sys.stderr)


def run(*args, timeout=15, check=True):
    p = subprocess.run(args, capture_output=True, text=True, timeout=timeout)
    if check and p.returncode != 0:
        raise RuntimeError(f"{' '.join(args)}: {p.stderr.strip() or p.returncode}")
    return p.stdout.strip()


def load(path, default):
    try:
        with open(path) as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


def save(path, data):
    os.makedirs(STATE_DIR, exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(data, f, indent=2, sort_keys=True)
        f.write("\n")
    os.replace(tmp, path)


class Skip(Exception):
    """Nothing to do for this item now (unavailable, or already low enough)."""


# ── Handlers: read() -> value, apply(original) -> applied, restore(original) ──


def toml_literal(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return "[ " + ", ".join(toml_literal(v) for v in value) + " ]"
    return "'" + str(value).replace("'", "") + "'"


def noctalia_get(key):
    try:
        out = run("noctalia", "msg", "config-get", key)
    except (RuntimeError, OSError, subprocess.TimeoutExpired) as e:
        raise Skip(f"Noctalia unavailable ({e})")
    if out.startswith("["):
        return [a or b for a, b in re.findall(r"'([^']*)'|\"([^\"]*)\"", out)]
    # Strings print as TOML literals ('still'), not bare.
    if len(out) >= 2 and out[0] == out[-1] and out[0] in "'\"":
        return out[1:-1]
    if out in ("true", "false"):
        return out == "true"
    try:
        return int(out)
    except ValueError:
        pass
    try:
        return float(out)
    except ValueError:
        return out


def noctalia_set(key, value):
    run("noctalia", "msg", "config-set", key, toml_literal(value))


class NoctaliaSetting:
    def __init__(self, p):
        self.key, self.value = p["key"], p["value"]

    def read(self):
        return noctalia_get(self.key)

    def apply(self, original):
        if original == self.value:
            raise Skip("already set")
        noctalia_set(self.key, self.value)
        return self.value

    def restore(self, original):
        noctalia_set(self.key, original)


class NoctaliaListRemove:
    def __init__(self, p):
        self.key, self.entry = p["key"], p["entry"]

    def read(self):
        value = noctalia_get(self.key)
        if not isinstance(value, list):
            raise Skip(f"{self.key} is not a list")
        return value

    def apply(self, original):
        if self.entry not in original:
            raise Skip(f"{self.entry} not in {self.key}")
        new = [v for v in original if v != self.entry]
        noctalia_set(self.key, new)
        return new

    def restore(self, original):
        noctalia_set(self.key, original)


class File:
    """A file that exists only while the item is applied (an Umbriel include)."""

    def __init__(self, p):
        self.path = os.path.expanduser(p["path"])
        self.content = p["content"]

    def read(self):
        try:
            with open(self.path) as f:
                return "present" if f.read() == self.content else "other"
        except OSError:
            return "absent"

    def apply(self, original):
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        tmp = self.path + ".tmp"
        with open(tmp, "w") as f:
            f.write(self.content)
        os.replace(tmp, self.path)
        return "present"

    def restore(self, original):
        with contextlib.suppress(FileNotFoundError):
            os.remove(self.path)


class Wled:
    def __init__(self, p):
        self.url, self.bri = p["url"].rstrip("/"), p["brightness"]

    def state(self):
        try:
            with urllib.request.urlopen(self.url + "/json/state", timeout=3) as r:
                return json.load(r)
        except (OSError, ValueError) as e:
            raise Skip(f"WLED unavailable ({e})")

    def post(self, bri):
        on = self.state().get("on", False)  # keep on/off as it is
        body = json.dumps({"on": on, "bri": bri}).encode()
        req = urllib.request.Request(
            self.url + "/json/state", body, {"Content-Type": "application/json"}
        )
        with urllib.request.urlopen(req, timeout=5) as r:
            r.read()

    def read(self):
        return self.state().get("bri")

    def apply(self, original):
        if original is not None and original <= self.bri:
            raise Skip(f"already at {original}")
        self.post(self.bri)
        return self.bri

    def restore(self, original):
        self.post(original)


class DdcCap:
    """Cap DDC brightness per connector; set through Noctalia so its OSD agrees."""

    def __init__(self, p):
        self.connectors, self.cap = p["connectors"], p["cap"]

    def buses(self):
        try:
            out = run("ddcutil", "detect", "--brief", timeout=20)
        except (RuntimeError, OSError, subprocess.TimeoutExpired) as e:
            raise Skip(f"ddcutil unavailable ({e})")
        buses, bus = {}, None
        for line in out.splitlines():
            line = line.strip()
            if line.startswith("I2C bus:"):
                bus = line.rsplit("-", 1)[-1]
            elif line.startswith("DRM connector:") and bus:
                conn = line.split(":", 1)[1].strip().split("-", 1)[-1]
                buses[conn] = bus
            elif line.startswith("Invalid display"):
                bus = None
        return {c: b for c, b in buses.items() if c in self.connectors}

    def read(self):
        values = {}
        for conn, bus in self.buses().items():
            with contextlib.suppress(RuntimeError, subprocess.TimeoutExpired):
                out = run("ddcutil", "--bus", bus, "--brief", "getvcp", "10")
                values[conn] = int(out.split()[3])  # "VCP 10 C <cur> <max>"
        if not values:
            raise Skip("no DDC display answered")
        return values

    def set(self, conn, value):
        try:
            run("noctalia", "msg", "brightness-set", conn, str(value))
        except (RuntimeError, OSError):
            run("ddcutil", "--bus", self.buses()[conn], "setvcp", "10", str(value))

    def apply(self, original):
        applied = dict(original)
        for conn, value in original.items():
            if value > self.cap:
                self.set(conn, self.cap)
                applied[conn] = self.cap
        if applied == original:
            raise Skip(f"already at or below {self.cap}")
        return applied

    def restore(self, original):
        for conn, value in original.items():
            self.set(conn, value)

    def changed(self, applied, current):
        # Only the connectors we lowered count; a hand change on one keeps it.
        return {c: v for c, v in current.items() if c in applied and v != applied[c]}


class PluginPause:
    """A Noctalia plugin service that pauses a systemd user unit."""

    def __init__(self, p):
        self.entry, self.unit = p["entry"], p["unit"]

    def read(self):
        out = run("systemctl", "--user", "show", self.unit,
                  "-p", "ActiveState", "-p", "FreezerState", check=False)
        props = dict(line.split("=", 1) for line in out.splitlines() if "=" in line)
        if props.get("ActiveState") != "active":
            return "inactive"
        return "frozen" if props.get("FreezerState") == "frozen" else "running"

    def ipc(self, event):
        run("noctalia", "msg", "plugin", self.entry, "all", event)

    def apply(self, original):
        if original != "running":
            raise Skip(f"unit {original}")
        self.ipc("pause")
        return "frozen"

    def restore(self, original):
        self.ipc("resume")


class Command:
    """read/apply/restore as commands; `when` is the read value to apply on."""

    def __init__(self, p):
        self.p = p

    def read(self):
        try:
            return run(*self.p["read"])
        except (RuntimeError, OSError) as e:
            raise Skip(str(e))

    def apply(self, original):
        if "when" in self.p and original != self.p["when"]:
            raise Skip(f"is {original}")
        run(*self.p["apply"])
        return self.p["applied"]

    def restore(self, original):
        run(*self.p["restore"])


class Report:
    """Done elsewhere (a system unit); only read for the state file."""

    def __init__(self, p):
        self.p = p

    def read(self):
        try:
            return run(*self.p["read"])
        except (RuntimeError, OSError) as e:
            raise Skip(str(e))


HANDLERS = {
    "noctalia-setting": NoctaliaSetting,
    "noctalia-list-remove": NoctaliaListRemove,
    "file": File,
    "wled-brightness": Wled,
    "ddc-cap": DdcCap,
    "plugin-pause": PluginPause,
    "command": Command,
    "report": Report,
}


def handler(item):
    return HANDLERS[item["handler"]](item.get("params", {}))


def changed(h, applied, current):
    if hasattr(h, "changed"):
        return bool(h.changed(applied, current))
    return current != applied


# ── Facts and modes ──


def power_profile():
    # power-profiles-daemon is the truth (the dashboard and powerprofilesctl
    # change it too); the hook's variable is only a fallback.
    with contextlib.suppress(RuntimeError, OSError, subprocess.TimeoutExpired):
        return run("powerprofilesctl", "get")
    return os.environ.get("NOCTALIA_POWER_PROFILE")


def steam_game():
    """A Steam game (native or Proton) runs under Steam's `reaper SteamLaunch AppId=N`."""
    for pid in os.listdir("/proc"):
        if not pid.isdigit():
            continue
        with contextlib.suppress(OSError):
            with open(f"/proc/{pid}/cmdline", "rb") as f:
                cmd = f.read(4096)
            if b"SteamLaunch\0" in cmd and b"AppId=" in cmd and b"AppId=0\0" not in cmd:
                return True
    return False


def fullscreen_window():
    """Umbriel shows a fullscreen window (a game outside Steam, or a video)."""
    with contextlib.suppress(RuntimeError, OSError, subprocess.TimeoutExpired, ValueError):
        windows = json.loads(run("umbriel", "windows", "--json", timeout=5))
        return any(w.get("fullscreen") and w.get("visible", True) and not w.get("minimized") for w in windows)
    return False


def game_running():
    return steam_game() or fullscreen_window()


def facts():
    f = {"power_profile": power_profile(), "toggles": load(TOGGLES, [])}
    if any("game" in m.get("when", {}) for m in MANIFEST.get("modes", [])):
        f["game"] = game_running()
    return f


def matches(f, key, value):
    if key == "toggle":
        return value in f.get("toggles", [])
    return f.get(key) == value


def watch(interval):
    """Re-sync when a game starts or stops (the game mode has no hook to call us)."""
    last = None
    while True:
        now = game_running()
        if now != last:
            with locked():
                sync(quiet=True)
            last = now
        time.sleep(interval)


def active_modes(f):
    return [
        m for m in MANIFEST.get("modes", [])
        if all(matches(f, k, v) for k, v in m.get("when", {}).items())
    ]


def after(item):
    """An item's follow-up command (e.g. tell an app to reload), run after apply or restore."""
    if item.get("after"):
        with contextlib.suppress(RuntimeError, OSError, subprocess.TimeoutExpired):
            run(*item["after"], timeout=60)


def wanted(modes, requested, overrides):
    """item id -> (mode, item): first active mode that lists the item wins."""
    out = {}
    for m in modes:
        for item in m["items"]:
            iid = item["id"]
            if iid in out or iid in overrides:
                continue
            if item.get("offer") and iid not in requested:
                continue
            out[iid] = (m, item)
    return out


def all_items():
    return {i["id"]: (m, i) for m in MANIFEST.get("modes", []) for i in m["items"]}


# ── Reconcile ──


@contextlib.contextmanager
def locked():
    os.makedirs(STATE_DIR, exist_ok=True)
    with open(os.path.join(STATE_DIR, "lock"), "w") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        yield


def sync(requested_add=(), override_add=(), quiet=False):
    state = load(STATE, {})
    saved = load(SAVED, {})
    f = facts()
    modes = active_modes(f)
    ids = [m["id"] for m in modes]
    previous = state.get("modes", [])
    entering = [m for m in ids if m not in previous]
    leaving = [m for m in previous if m not in ids]
    # Offers taken and per-item overrides last while the same modes stay active.
    requested = [] if entering or leaving else list(state.get("requested", []))
    overrides = [] if entering or leaving else list(state.get("overrides", []))
    requested += [i for i in requested_add if i not in requested]
    overrides += [i for i in override_add if i not in overrides]
    want = wanted(modes, requested, overrides)
    items = {}
    restored, kept = [], []

    for iid in list(saved):
        if iid in want:
            continue
        rec = saved.pop(iid)
        _, item = all_items().get(iid, (None, rec.get("item")))
        if item is None:
            continue
        h = handler(item)
        try:
            current = h.read()
            if changed(h, rec["applied"], current):
                kept.append(item["label"])
                log(f"{iid}: changed by hand ({current}), kept")
            else:
                h.restore(rec["original"])
                after(item)
                restored.append(item["label"])
        except Skip as e:
            log(f"{iid}: restore skipped: {e}")
        except Exception as e:  # one item failing never stops the others
            log(f"{iid}: restore failed: {e}")

    for iid, (mode, item) in want.items():
        h = handler(item)
        entry = {"label": item["label"], "glyph": item.get("glyph", ""),
                 "mode": mode["id"], "summary": item.get("summary", "")}
        try:
            if item["handler"] == "report":
                entry.update(status="applied", value=h.read())
            elif iid in saved:
                current = h.read()
                if changed(h, saved[iid]["applied"], current):
                    entry["status"] = "changed"  # by hand; restore leaves it
                else:
                    entry["status"] = "applied"
            else:
                original = h.read()
                applied = h.apply(original)
                after(item)
                saved[iid] = {"original": original, "applied": applied, "item": item}
                entry["status"] = "applied"
        except Skip as e:
            entry.update(status="skipped", reason=str(e))
        except Exception as e:
            entry.update(status="failed", reason=str(e))
            log(f"{iid}: apply failed: {e}")
        items[iid] = entry

    offers = {}
    for m in modes:
        for item in m["items"]:
            if item.get("offer") and item["id"] not in want:
                with contextlib.suppress(Skip, Exception):
                    # A command offer shows only while it would change something.
                    if "when" not in item.get("params", {}) or \
                            handler(item).read() == item["params"]["when"]:
                        offers[item["id"]] = {"label": item["label"],
                                              "action": item.get("action", item["label"])}

    since = state.get("since") if not entering and not leaving else None
    new_state = {
        "modes": ids,
        "mode_labels": {m["id"]: m["label"] for m in modes},
        "mode_kinds": {m["id"]: m.get("kind", "profile") for m in modes},
        "leave": modes[0].get("leave") if modes else None,
        "since": since or (datetime.datetime.now().astimezone().isoformat(timespec="seconds") if ids else None),
        "facts": f,
        "items": items,
        "offers": offers,
        "requested": requested,
        "overrides": overrides,
        "kept": kept,
    }
    save(SAVED, saved)
    save(STATE, new_state)
    # Modes switched by hand (toggles) need no notification: the click is the feedback.
    loud = {m["id"] for m in MANIFEST.get("modes", []) if m.get("notify", True)}
    entering = [m for m in entering if m in loud]
    leaving = [m for m in leaving if m in loud]
    if not quiet:
        notify(modes, entering, leaving, items, offers, restored, kept)
    return new_state


# ── Notifications ──


def notify(modes, entering, leaving, items, offers, restored, kept):
    if not entering and not leaving:
        return
    with contextlib.suppress(Exception):
        run("systemctl", "--user", "stop", "erebor-modes-notify.service", check=False)
    exe = shutil.which("erebor-modes") or sys.argv[0]
    if entering:
        m = next(m for m in modes if m["id"] == entering[0])
        done = [i["label"] for i in items.values() if i["status"] == "applied"]
        body = ", ".join(done) or "nothing to change"
        actions = []
        if m.get("leave"):
            actions.append(["leave", m["leave"]["label"]])
        for iid, o in offers.items():
            actions.append([f"offer:{iid}", o["action"]])
        cmd = ["notify-send", "-a", "erebor-modes", "-i", m.get("icon", "dialog-information"),
               "--wait", m["label"] + " on", body]
        for key, label in actions:
            cmd += ["-A", f"{key}={label}"]
        payload = json.dumps({"cmd": cmd, "mode": m["id"]})
        subprocess.run(["systemd-run", "--user", "--collect", "--quiet",
                        "--unit=erebor-modes-notify", exe, "_notify", payload],
                       capture_output=True)
    else:
        labels = ", ".join(leaving)
        body = ("Restored: " + ", ".join(restored)) if restored else "Nothing to restore"
        if kept:
            body += ". Kept your changes: " + ", ".join(kept)
        subprocess.run(["notify-send", "-a", "erebor-modes", "-i", "dialog-information",
                        f"{labels} off", body], capture_output=True)


def notify_wait(payload):
    p = json.loads(payload)
    action = run(*p["cmd"], timeout=86400, check=False)
    mode = next((m for m in MANIFEST.get("modes", []) if m["id"] == p["mode"]), None)
    if action == "leave" and mode and mode.get("leave"):
        run(*mode["leave"]["command"], check=False)
    elif action.startswith("offer:"):
        with locked():
            sync(requested_add=[action[6:]], quiet=True)


# ── CLI ──


def main():
    ap = argparse.ArgumentParser(prog="erebor-modes", description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("sync", help="apply or restore items for the active modes")
    st = sub.add_parser("status", help="print the state")
    st.add_argument("--json", action="store_true")
    ap_item = sub.add_parser("request", help="apply an offered item (e.g. hdr)")
    ap_item.add_argument("item")
    ov = sub.add_parser("override", help="restore one item while the modes stay active")
    ov.add_argument("item")
    tg = sub.add_parser("toggle", help="switch a toggle mode (e.g. reduce-transparency)")
    tg.add_argument("mode")
    tg.add_argument("to", nargs="?", choices=["on", "off", "toggle"], default="toggle")
    sub.add_parser("manifest", help="print the manifest")
    wt = sub.add_parser("watch", help="keep the game mode in step with running games")
    wt.add_argument("--interval", type=float, default=3.0)
    nt = sub.add_parser("_notify")
    nt.add_argument("payload")
    a = ap.parse_args()

    if a.cmd == "manifest":
        print(json.dumps(MANIFEST, indent=2))
    elif a.cmd == "status":
        state = load(STATE, {"modes": []})
        if a.json:
            print(json.dumps(state, indent=2))
        else:
            print("modes:", ", ".join(state.get("modes", [])) or "none")
            for iid, i in state.get("items", {}).items():
                extra = f" ({i['reason']})" if i.get("reason") else ""
                print(f"  {iid}: {i['status']}{extra}")
            for iid, o in state.get("offers", {}).items():
                print(f"  offer {iid}: {o['action']}")
    elif a.cmd == "watch":
        watch(a.interval)
    elif a.cmd == "_notify":
        notify_wait(a.payload)
    elif a.cmd == "toggle":
        kinds = {m["id"]: m.get("kind") for m in MANIFEST.get("modes", [])}
        if kinds.get(a.mode) != "toggle":
            sys.exit(f"erebor-modes: {a.mode} is not a toggle mode")
        with locked():
            toggles = load(TOGGLES, [])
            on = a.mode not in toggles if a.to == "toggle" else a.to == "on"
            toggles = [t for t in toggles if t != a.mode] + ([a.mode] if on else [])
            save(TOGGLES, toggles)
            sync()
        print("on" if on else "off")
    else:
        if a.cmd in ("request", "override") and a.item not in all_items():
            sys.exit(f"erebor-modes: unknown item {a.item}")
        with locked():
            sync(requested_add=[a.item] if a.cmd == "request" else (),
                 override_add=[a.item] if a.cmd == "override" else (),
                 quiet=a.cmd != "sync")


if __name__ == "__main__":
    main()
